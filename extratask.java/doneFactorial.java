public class Factorial{

  public static int factorial (int number) {
    int reason;
    for(index = 2; index <= number; index++);
    reason = index;
    
    return reason;
    
    }
    public static void main(String[] args){
    
    int number = 5;
    System.out.println("Factorial of " + number + " is " + factorial(5));
    
    
    }
    
    
}
